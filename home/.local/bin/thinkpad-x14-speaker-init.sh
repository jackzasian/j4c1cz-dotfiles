#!/bin/bash
# ThinkPad X14 Gen 1 (ALC257 / 17aa:513d) speaker init
# Software routing + Realtek amp coef init. Requires kernel quirk for full fix.
set -euo pipefail

DEV=/dev/snd/hwC0D0
for i in $(seq 1 30); do
  [[ -e "$DEV" ]] && break
  sleep 1
done
[[ -e "$DEV" ]] || { echo "HDA codec not found: $DEV" >&2; exit 1; }

run_verb() {
  hda-verb "$DEV" "$1" "$2" "$3" >/dev/null 2>&1 || true
}

# Disable false headphone jack detect (stops OUT HP stealing speaker path)
run_verb 0x20 0x500 0x1b
run_verb 0x20 0x400 0x8000
run_verb 0x20 0x400 0x0000
run_verb 0x21 0x707 0x00
run_verb 0x21 0x709 0x00
run_verb 0x1b 0x707 0x00

# Realtek speaker amp coef init (Legion/Yoga sequence; closest known ThinkPad match)
run_verb 0x20 0x500 0x24
run_verb 0x20 0x400 0x41
run_verb 0x20 0x500 0x26
run_verb 0x20 0x400 0xc
run_verb 0x20 0x400 0x0
run_verb 0x20 0x400 0x1a
run_verb 0x20 0x400 0xb020
run_verb 0x20 0x500 0x26
run_verb 0x20 0x400 0x2
run_verb 0x20 0x400 0x0
run_verb 0x20 0x400 0x0
run_verb 0x20 0x400 0xb020
run_verb 0x20 0x500 0x24
run_verb 0x20 0x400 0x42
run_verb 0x20 0x500 0x26
run_verb 0x20 0x400 0xc
run_verb 0x20 0x400 0x0
run_verb 0x20 0x400 0x2a
run_verb 0x20 0x400 0xb020
run_verb 0x20 0x500 0x26
run_verb 0x20 0x400 0x2
run_verb 0x20 0x400 0x0
run_verb 0x20 0x400 0x0
run_verb 0x20 0x400 0xb020

run_verb 0x14 0x707 0x40
run_verb 0x14 0x70a 0x00

amixer -c 0 sset 'Auto-Mute Mode' Disabled >/dev/null 2>&1 || true
amixer -c 0 sset 'Speaker' 100% unmute >/dev/null 2>&1 || true
amixer -c 0 sset 'Headphone' 0% mute >/dev/null 2>&1 || true
amixer -c 0 sset 'Master' 100% unmute >/dev/null 2>&1 || true

# Disable runtime HDA power save (resets amp state)
if [[ -w /sys/module/snd_hda_intel/parameters/power_save ]]; then
  echo 0 > /sys/module/snd_hda_intel/parameters/power_save 2>/dev/null || true
fi
